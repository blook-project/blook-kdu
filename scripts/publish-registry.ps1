# blook-kdu: publish the package manifest to the org xmake registry.
#
# Usage:
#   pwsh scripts/publish-registry.ps1 -Package blook-kdu -Version 0.1.0 `
#        -Zip artifacts/blook-kdu-0.1.0-windows-x64.zip
#   add -DryRun to only print the change.
#
# The registry lives at https://github.com/blook-project/blook-xmake-repo and is
# updated with the local `gh` credentials (no org secret needed on the dev host).
[CmdletBinding()]
param(
    [string] $Root = (Split-Path -Parent $PSScriptRoot),
    [string] $Package = 'blook-kdu',
    [Parameter(Mandatory = $true)][string] $Version,
    [string] $Zip = '',
    [string] $RegistryRepo = 'blook-project/blook-xmake-repo',
    [switch] $DryRun
)

$ErrorActionPreference = 'Stop'
Set-Location $Root

if (-not $Zip) {
    $Zip = Join-Path $Root "artifacts/$Package-$Version-windows-x64.zip"
}
if (-not (Test-Path $Zip)) {
    throw "release asset not found: $Zip"
}
$hash = (Get-FileHash $Zip -Algorithm SHA256).Hash.ToLower()
$assetName = Split-Path -Leaf $Zip

$manifest = @"
-- $Package $Version - generated by scripts/publish-registry.ps1
package("$Package")
    set_homepage("https://github.com/blook-project/blook-kdu")
    set_description("Self-contained Windows kernel driver exploitation toolkit with manual mapping, kernel payload and SDK")
    set_license("MIT")
    set_kind("library", {headeronly = false})

    add_urls("https://github.com/blook-project/blook-kdu/releases/download/v`$(version)/$Package-`$(version)-windows-x64.zip")
    add_versions("$Version", "$hash")

    on_install("windows|x64", function (package)
        os.cp("include", package:installdir())
        os.cp("bin", package:installdir())
        os.cp("lib", package:installdir())
        os.cp("xmake-package/xmake.lua", package:installdir("xmake-package"))
    end)

    on_test(function (package)
        assert(os.isfile(path.join(package:installdir(), "include/blook/kdu/kdu.h")))
    end)
package_end()
"@

Write-Host "package : $Package $Version"
Write-Host "asset   : $assetName"
Write-Host "sha256  : $hash"
if ($DryRun) {
    Write-Host "--- manifest (dry run) ---"
    Write-Host $manifest
    return
}

$temp = Join-Path ([System.IO.Path]::GetTempPath()) ("blook-registry-" + [guid]::NewGuid())
try {
    gh repo clone $RegistryRepo $temp -- --depth 1 | Out-Null
    $packageDir = Join-Path $temp "packages/$($Package[0])/$Package"
    New-Item -ItemType Directory -Force $packageDir | Out-Null
    Set-Content -Path (Join-Path $packageDir 'xmake.lua') -Value $manifest -Encoding UTF8
    Push-Location $temp
    try {
        git add .
        git -c user.name="MicroBlock" `
            -c user.email="66859419+std-microblock@users.noreply.github.com" `
            commit -m "$Package: publish $Version ($($hash.Substring(0, 12)))"
        git push origin HEAD
    } finally {
        Pop-Location
    }
    Write-Host "registry updated: $RegistryRepo packages/$($Package[0])/$Package"
} finally {
    if (Test-Path $temp) { Remove-Item $temp -Recurse -Force }
}
