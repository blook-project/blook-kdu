# blook-kdu: turn the built kernel payload (.sys) into a C array header that is
# compiled into the CLI/ipc library, so a single self-contained exe carries the
# payload image and can map it at runtime.
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string] $InputFile,
    [Parameter(Mandatory = $true)][string] $OutputFile,
    [string] $Symbol = "kdu_payload_image"
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path $InputFile)) {
    throw "payload image not found: $InputFile"
}
$bytes = [System.IO.File]::ReadAllBytes($InputFile)
$outDir = Split-Path -Parent $OutputFile
if (-not (Test-Path $outDir)) {
    New-Item -ItemType Directory -Force $outDir | Out-Null
}

$builder = New-Object System.Text.StringBuilder
[void]$builder.AppendLine('// Generated by scripts/gen-payload-blob.ps1 - do not edit.')
[void]$builder.AppendLine('#pragma once')
[void]$builder.AppendLine('')
[void]$builder.AppendLine('static const unsigned char ' + $Symbol + '[] = {')
$line = New-Object System.Text.StringBuilder
for ($index = 0; $index -lt $bytes.Length; $index++) {
    [void]$line.Append(('0x{0:x2},' -f $bytes[$index]))
    if (($index % 16) -eq 15) {
        [void]$builder.AppendLine('    ' + $line.ToString())
        $line.Clear() | Out-Null
    }
}
if ($line.Length -gt 0) {
    [void]$builder.AppendLine('    ' + $line.ToString())
}
[void]$builder.AppendLine('};')
[void]$builder.AppendLine(('static const unsigned int ' + $Symbol + '_size = {0};' -f $bytes.Length))
[void]$builder.AppendLine(('static const unsigned int ' + $Symbol + '_sha256 = 0; // filled by release tooling'))

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($OutputFile, $builder.ToString(), $utf8)
Write-Host ("embedded payload blob: {0} bytes -> {1}" -f $bytes.Length, $OutputFile)


