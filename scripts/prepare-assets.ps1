# blook-kdu: build the embedded-driver RCDATA table.
#
# Copies every driver blob referenced by an exploit's .rc (plus the manual-map
# victim driver) into build/generated/assets and writes src/assets.rc. The blobs
# are embedded exactly as shipped: no Authenticode stripping and no re-signing,
# so vendor signatures (and any blocklist/revocation behaviour) stay intact.
#
# Outputs (git-ignored):
#   build/generated/assets/<owner>/<binary>   copies of the source blobs
#   src/assets.rc                             RCDATA table for the CLI
[CmdletBinding()]
param(
    [string] $Root = (Split-Path -Parent $PSScriptRoot),
    [switch] $Force
)

$ErrorActionPreference = 'Stop'
$generated = Join-Path $Root 'build/generated'
$assetsDir = Join-Path $generated 'assets'
$rcPath = Join-Path $Root 'src/assets.rc'
New-Item -ItemType Directory -Force $assetsDir | Out-Null
New-Item -ItemType Directory -Force $generated | Out-Null

$sources = @()
foreach ($exploit in Get-ChildItem (Join-Path $Root 'src/exploits') -Directory) {
    if ($exploit.Name -in @('common', 'data')) { continue }
    $dataDir = Join-Path $exploit.FullName 'data'
    if (-not (Test-Path $dataDir)) { continue }
    $resourceHeader = Join-Path $exploit.FullName 'resource.h'
    if (-not (Test-Path $resourceHeader)) { continue }
    $defines = @{}
    foreach ($line in Get-Content $resourceHeader) {
        if ($line -match '^\s*#define\s+(IDR_\w+)\s+(\d+)') {
            $defines[$matches[1]] = [int]$matches[2]
        }
    }
    foreach ($rc in Get-ChildItem $dataDir -Filter '*.rc') {
        $content = Get-Content $rc.FullName -Raw
        foreach ($match in [regex]::Matches(
                     $content, '^\s*(IDR_\w+)\s+RCDATA\s+"([^"]+)"', 'Multiline')) {
            $symbol = $match.Groups[1].Value
            $binaryName = $match.Groups[2].Value
            if (-not $defines.ContainsKey($symbol)) { continue }
            $source = Join-Path $dataDir $binaryName
            if (-not (Test-Path $source)) { continue }
            $sources += [pscustomobject]@{
                id = $defines[$symbol]
                owner = $exploit.Name
                binary = $binaryName
                source = $source
            }
        }
    }
}

# Manual mapper victim driver.
$victimHeader = Join-Path $Root 'src/loader/resource.h'
$victimId = 9101
if (Test-Path $victimHeader) {
    foreach ($line in Get-Content $victimHeader) {
        if ($line -match '^\s*#define\s+IDR_VICTIM_PROCEXP\s+(\d+)') {
            $victimId = [int]$matches[1]
        }
    }
}
$victimBin = Get-ChildItem (Join-Path $Root 'src/loader/data') -Filter '*.bin' |
             Select-Object -First 1
if ($victimBin) {
    $sources += [pscustomobject]@{
        id = $victimId
        owner = 'loader'
        binary = $victimBin.Name
        source = $victimBin.FullName
    }
}

$entries = New-Object System.Collections.Generic.List[string]
$copied = 0
foreach ($source in $sources) {
    $destinationDir = Join-Path $assetsDir $source.owner
    New-Item -ItemType Directory -Force $destinationDir | Out-Null
    $destination = Join-Path $destinationDir $source.binary
    $upToDate = (Test-Path $destination) -and
                ((Get-Item $destination).LastWriteTimeUtc -ge
                 (Get-Item $source.source).LastWriteTimeUtc)
    if ($upToDate -and -not $Force) {
        Write-Verbose "cached: $($source.binary)"
    } else {
        Copy-Item $source.source $destination -Force
        $copied++
    }
    $relative = '../build/generated/assets/' + $source.owner + '/' + $source.binary
    $entries.Add(('{0} RCDATA "{1}"' -f $source.id, $relative))
}

$rc = @('#include <winres.h>',
        '// Generated by scripts/prepare-assets.ps1 - do not edit.',
        '// Driver blobs are embedded exactly as shipped (original signatures).')
$rc += $entries
Set-Content -Path $rcPath -Value $rc -Encoding ascii
Write-Host ("prepared {0} embedded driver asset(s): {1} copied, {2} cached" -f `
            $entries.Count, $copied, ($entries.Count - $copied))
